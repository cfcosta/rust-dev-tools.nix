"""Write the workspace that compiles one planned crate exactly as a build needs it.

Usage: make-unit.py SPEC.json OUT

The workspace's own package depends on the crate and on everything the crate
needs, each pinned to its version with its resolved features and no others.
Cargo then resolves every one of them to the features the original build
gave it, so their units match that build's. Crates built for the host are
build dependencies, the rest normal ones.
"""

import json
import pathlib
import sys

import toml

spec = json.load(open(sys.argv[1]))
out = pathlib.Path(sys.argv[2])
(out / "src").mkdir(parents=True)

dependencies = {}
build_dependencies = {}
for dep in spec["deps"]:
    entry = {
        "package": dep["name"],
        "version": "=" + dep["version"],
        "default-features": False,
        "features": dep["features"],
    }
    (build_dependencies if dep["host"] else dependencies)[dep["alias"]] = entry

manifest = {
    "package": {
        "name": "rdt-unit",
        "version": "0.0.0",
        "edition": "2021",
        "build": "build.rs",
        "publish": False,
    },
    "lib": {"path": "src/lib.rs"},
    "dependencies": dependencies,
    "build-dependencies": build_dependencies,
    "workspace": {},
}
if spec["profile"]:
    manifest["profile"] = spec["profile"]
(out / "Cargo.toml").write_text(toml.dumps(manifest))
(out / "build.rs").write_text("fn main() {}\n")
(out / "src/lib.rs").write_text("")

if spec["config"] is not None:
    (out / ".cargo").mkdir()
    (out / ".cargo/config.toml").write_text(spec["config"])


def quote(value):
    return json.dumps(value)


lines = [
    "# This file is automatically @generated by Cargo.",
    "# It is not intended for manual editing.",
    f"version = {spec['lockVersion']}",
    "",
]
root = {
    "name": "rdt-unit",
    "version": "0.0.0",
    "dependencies": sorted({f"{dep['name']} {dep['version']}" for dep in spec["deps"]}),
}
for package in sorted(spec["packages"] + [root], key=lambda p: (p["name"], p["version"])):
    lines.append("[[package]]")
    for field in ("name", "version", "source", "checksum"):
        if field in package:
            lines.append(f"{field} = {quote(package[field])}")
    if package.get("dependencies"):
        lines.append("dependencies = [")
        lines.extend(f" {quote(ref)}," for ref in package["dependencies"])
        lines.append("]")
    lines.append("")
(out / "Cargo.lock").write_text("\n".join(lines))
